"""
elife_simulate.py
=================
Agents of elife_models.py playing the EXACT task of the experiment, for
parameter recovery, model confusion and the non-anticipating-agent control.

Task (as in the rig; criterion from value_getTrialStatsMore.m):
  * two rules, 70:10 and 10:70, alternating at every block switch;
  * criterion: the 10th choice (cumulative, not consecutive) of the
    high-probability side within the block;
  * after the criterion, L_Random more trials are added, L_Random drawn from
    the empirical distribution of complete blocks (block_trial_random_added of
    every block that is not the last of its session, naive cohort);
  * reward: Bernoulli(p of the chosen side).
Misses are not generated by the agent: a simulated session reproduces the
length and the miss positions of a real session (missed trials have no choice
and no outcome, and count as trials for L_Random, as in the rig).

The agent at trial t chooses from exactly the probability its likelihood
assigns (elife_models kernels), so simulation and fitting use the same model.

tau (trials since criterion) is computed from the simulated block structure
with the same rule as belief_vhr.prepare_vhr; the variable-hazard agents use
it online (the hazard of the step into t+1 uses tau[t+1], known at the end of
trial t because tau only depends on whether the criterion has been met).
"""

from __future__ import annotations

import numpy as np
import pandas as pd
from numba import njit

import elife_models as em

KIND = {"wsls": 0, "q": 1, "belief": 2, "r3": 3}


@njit(cache=True)
def _sim_session(kind, x, forget, use_ck, bilateral, vhr, miss, lrand, seed, first_rule):
    """Simulate one session. x: parameter vector; miss: (n,) bool; lrand:
    samples of L_Random to draw from. Returns c, r, rule(1 = left high),
    tau, block_idx, ttc_per_trial."""
    np.random.seed(seed)
    n = len(miss)
    c = np.full(n, np.nan)
    r = np.full(n, np.nan)
    rule = np.zeros(n)
    tau = np.zeros(n)
    blk = np.zeros(n)
    # --- task state
    cur_rule = first_rule                    # 1: left = 0.7, 2: right = 0.7
    hits = 0
    crit_met = False
    since_crit = 0
    L = 0
    b = 0
    # --- agent state
    vr = vl = 0.5
    ckr = ckl = 0.0
    p0 = p1 = 0.5                            # belief over left = (0.1, 0.7)
    mu_l = 0.4
    mu_r = 0.4
    for t in range(n):
        rule[t] = cur_rule
        blk[t] = b
        tau[t] = since_crit if crit_met else 0.0
        # ---------------- choice probability
        if kind == 0:                        # WSLS
            p = x[0]
            if t == 0 or np.isnan(c[t - 1]):
                pr = 0.5
            elif r[t - 1] > 0:
                pr = p if c[t - 1] == 1 else 1 - p
            else:
                pr = 1 - p if c[t - 1] == 1 else p
        elif kind == 3:                      # R3 agent
            if t == 0 or np.isnan(c[t - 1]):
                pr = 0.5
            else:
                if r[t - 1] > 0:
                    ps = x[0] + (1 - x[0]) * (0.5 + 0.5 * x[1])
                else:
                    ps = x[0] + (1 - x[0]) * (0.5 - 0.5 * x[2])
                pr = ps if c[t - 1] == 1 else 1 - ps
        elif kind == 1:                      # Q family
            beta = x[2] if forget == 2 else x[1]
            bck = 0.0
            if use_ck:
                bck = x[4] if forget == 2 else x[3]
            Vr = beta * vr + bck * ckr
            Vl = beta * vl + bck * ckl
            pr = 1.0 / (1.0 + np.exp(Vl - Vr))
        else:                                # belief family (exact Bayes)
            if vhr:
                beta = x[2]
                bck = x[4] if use_ck else 0.0
            elif bilateral:
                beta = x[4]
                bck = x[5]
            else:
                beta = x[1]
                bck = x[3] if use_ck else 0.0
            Vr = beta * mu_r + bck * ckr
            Vl = beta * mu_l + bck * ckl
            pr = 1.0 / (1.0 + np.exp(Vl - Vr))
        # ---------------- act
        if not miss[t]:
            c[t] = 1.0 if np.random.random() < pr else -1.0
            p_side = (0.1 if cur_rule == 1 else 0.7) if c[t] == 1 else (0.7 if cur_rule == 1 else 0.1)
            r[t] = 1.0 if np.random.random() < p_side else 0.0
            high = (c[t] == -1 and cur_rule == 1) or (c[t] == 1 and cur_rule == 2)
            if high and not crit_met:
                hits += 1
                if hits >= 10:
                    crit_met = True
                    since_crit = -1          # the criterion trial itself has tau 0
                    L = lrand[np.random.randint(len(lrand))]
        # ---------------- task clock (counts every trial, missed or not)
        switch_now = False
        if crit_met:
            since_crit += 1
            if since_crit >= L:
                switch_now = True
        tau_next = 0.0
        if crit_met and not switch_now:
            tau_next = float(since_crit)
        # ---------------- agent update
        ch = c[t]
        if kind == 1 and not np.isnan(ch):
            alpha = x[0]
            decay = 0.0 if forget == 0 else (alpha if forget == 1 else x[1])
            if use_ck:
                ack = x[3] if forget == 2 else x[2]
                if ch == 1:
                    ckr = (1 - ack) * ckr + ack
                    ckl = (1 - ack) * ckl
                else:
                    ckr = (1 - ack) * ckr
                    ckl = (1 - ack) * ckl + ack
            if ch == 1:
                vr = vr + alpha * (r[t] - vr)
                if forget > 0:
                    vl = (1 - decay) * vl
            else:
                vl = vl + alpha * (r[t] - vl)
                if forget > 0:
                    vr = (1 - decay) * vr
        if kind == 2 and not np.isnan(ch):
            if vhr:
                H = 1.0 / (1.0 + np.exp(-(x[0] + x[1] * tau_next)))
                HL = HR = H
                aL = aR = x[3] if use_ck else 0.0
            elif bilateral:
                HL, HR, aL, aR = x[0], x[1], x[2], x[3]
            else:
                HL = HR = x[0]
                aL = aR = x[2] if use_ck else 0.0
            H = HR if ch == 1 else HL
            p0 = p0 * (1 - H) + 0.5 * H
            p1 = p1 * (1 - H) + 0.5 * H
            s = p0 + p1
            p0, p1 = p0 / s, p1 / s
            # exact Bayes: P(outcome | state), state = left reward prob 0.1 / 0.7
            if ch == -1:
                l0 = 0.1 if r[t] == 1 else 0.9
                l1 = 0.7 if r[t] == 1 else 0.3
            else:                            # right prob is 0.7 / 0.1 in states 0 / 1
                l0 = 0.7 if r[t] == 1 else 0.3
                l1 = 0.1 if r[t] == 1 else 0.9
            p0, p1 = p0 * l0, p1 * l1
            s = p0 + p1
            p0, p1 = p0 / s, p1 / s
            mu_l = 0.1 * p0 + 0.7 * p1
            mu_r = 0.7 * p0 + 0.1 * p1
            if use_ck:
                if ch == 1:
                    ckr = (1 - aR) * ckr + aR
                    ckl = (1 - aR) * ckl
                else:
                    ckr = (1 - aL) * ckr
                    ckl = (1 - aL) * ckl + aL
        # ---------------- block switch
        if switch_now:
            cur_rule = 2 if cur_rule == 1 else 1
            hits = 0
            crit_met = False
            since_crit = 0
            b += 1
    return c, r, rule, tau, blk


def empirical_lrandom(df: pd.DataFrame) -> np.ndarray:
    """L_Random of complete blocks (not the last block of a session)."""
    b = df.groupby(["session_file", "block_idx"])["block_trial_random_added"].first().reset_index()
    last = b.groupby("session_file")["block_idx"].transform("max")
    v = b.loc[b["block_idx"] < last, "block_trial_random_added"].dropna().to_numpy()
    return v.astype(np.int64)


def simulate_session(model, params, miss, lrand, seed, first_rule=1):
    """Simulate one session of `model` with parameters in the MATLAB order.
    Belief models always use the exact Bayes update."""
    m = em.MODELS[model] if isinstance(model, str) else model
    o = m.opts
    c, r, rule, tau, blk = _sim_session(
        KIND[m.kind], np.asarray(params, float), int(o.get("forget", 0)),
        bool(o.get("ck", False)), bool(o.get("bilateral", False)), bool(o.get("vhr", False)),
        np.asarray(miss, np.bool_), np.asarray(lrand, np.int64), int(seed), int(first_rule))
    return {"c": c, "r": r, "rule": rule, "tau": tau, "block_idx": blk}


def simulate_like(model, params, sessions, lrand, seed=0):
    """Simulate a dataset with the same number, length and miss pattern of
    sessions as `sessions` (list of dicts with 'c'). Returns list of dicts
    with c, r, tau, rule, block_idx."""
    rng = np.random.default_rng(seed)
    out = []
    for s in sessions:
        miss = np.isnan(s["c"])
        out.append(simulate_session(model, params, miss, lrand,
                                    int(rng.integers(2 ** 31 - 1)), int(rng.integers(1, 3))))
    return out
