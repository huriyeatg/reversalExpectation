"""
elife_recovery.py
=================
Phase 2, steps 3 and 4, on simulated data from the EXACT task
(elife_simulate.py: 10-hit criterion + empirical L_Random, real session
lengths and miss positions):

  3. Parameter recovery and model confusion.
     Every generating model g is simulated once per animal with that animal's
     fitted parameters (reset scheme, full data, from elife_model_comparison.py),
     on that animal's sessions. Every candidate model f is then fitted to each
     simulated dataset:
       - in-sample (BIC, AIC), and
       - 2-fold cross-validation by session (odd/even sessions), held-out LL
         per trial on the common trial set of elife_model_comparison.py.
     Outputs the confusion matrices P(f wins | g generated), and the
     correlation between true and recovered parameters for f = g.

  4. Non-anticipating agents on the criterion-dependent task.
     The fit of belief_vhr / belief_CK_vhr to data generated by models WITHOUT
     anticipation (constant hazard, Q-learning, WSLS, R3) gives the hazard slope
     b that the task structure alone produces. It is compared with the b fitted
     to the real animals (paired by animal). The behavioural signature P(choose
     the pre-switch worse side | tau) in the L_Random window is computed for the
     animals and for every simulated agent.

Belief models are simulated and fitted with the exact Bayes update; the
literal MATLAB variants (belief, belief_CK) cannot be simulated as agents of the
same model and are left out here.

Inputs  (relative to reversalExpectation_py/):
    analysis/bandit_R71_lesion.csv
    analysis/elife_model_comparison/full_fits.csv
Outputs (analysis/elife_recovery/):
    fits_checkpoint.csv      generator, animal, fitted model: nll, bic, aic, CV, params
    signature_checkpoint.csv generator ("real" for the animals), animal, tau bin, P(worse)
    confusion_bic.csv, confusion_aic.csv, confusion_cv.csv
    param_recovery.csv
    hazard_slope_control.csv
    report.txt

Usage (from reversalExpectation_py/):
    python behavior/beh_models/elife_recovery.py --jobs 2
"""

from __future__ import annotations

import argparse
import sys
import time
from multiprocessing import Pool
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import spearmanr, pearsonr, wilcoxon

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import elife_models as em                    # noqa: E402
import elife_simulate as es                  # noqa: E402
import elife_model_comparison as cmpm        # noqa: E402

PY_ROOT = HERE.parents[1]
CSV_PATH = PY_ROOT / "analysis" / "bandit_R71_lesion.csv"
FITS_CSV = PY_ROOT / "analysis" / "elife_model_comparison" / "full_fits.csv"
OUT_DIR = PY_ROOT / "analysis" / "elife_recovery"

MODELS = ["WSLS", "Q_RPE", "DFQ_RPE", "FQ_RPE", "FQ_RPE_CK", "DFQ_RPE_CK",
          "belief_exact", "belief_CK_exact", "belief_vhr", "belief_CK_vhr", "R3_agent"]
NON_ANTICIPATING = [m for m in MODELS if not m.endswith("_vhr")]
N_STARTS = 5
TAU_MAX = 15


# ---------------------------------------------------------------------------
def signature(sess):
    """P(choose the block's worse side | tau) in the L_Random phase.
    sess: list of dicts with c, tau, and either rule (1 = left high) or hr_side."""
    rows = []
    for s in sess:
        c, tau = s["c"], s["tau"]
        high = s["hr_side"] if "hr_side" in s else np.where(s["rule"] == 1, -1.0, 1.0)
        # L_Random phase: tau > 0, or tau == 0 on the trial after the criterion;
        # restrict to tau >= 1 to avoid the ambiguity of tau == 0
        ok = ~np.isnan(c) & (tau >= 1) & (tau <= TAU_MAX)
        worse = (c != high).astype(float)
        rows.append(pd.DataFrame({"tau": tau[ok], "worse": worse[ok]}))
    d = pd.concat(rows)
    return d.groupby("tau")["worse"].agg(["mean", "size"]).reset_index()


def fit_all(sim, n_starts, seed):
    """Fit every candidate model to one simulated dataset (reset scheme)."""
    c, r, st = em.build_reset([(s["c"], s["r"]) for s in sim])
    tau = np.concatenate([s["tau"] for s in sim])
    sid = np.repeat(np.arange(len(sim)), [len(s["c"]) for s in sim])
    halves = [np.arange(len(sim)) % 2 == h for h in (0, 1)]
    out, best, best_h = {}, {}, {}
    for f in cmpm.fit_order(MODELS):
        m = em.MODELS[f]
        o = em.fit(f, c, r, st, True, n_starts=n_starts, seed=seed, tau=tau,
                   extra_x0=cmpm.nested_starts(f, best.get(cmpm.NESTS.get(f))))
        best[f] = o["params"]
        n_resp = int(np.sum(~np.isnan(c)))
        row = {"nll": o["negloglike"], "bic": o["bic"],
               "aic": 2 * m.n_params + 2 * o["negloglike"],
               **{f"par_{l}": v for l, v in zip(m.labels, o["params"])}}
        # 2-fold CV by session
        ll_cv, n_cv = 0.0, 0
        for h in (0, 1):
            tr = [s for s, k in zip(sim, halves[h]) if k]
            te = [s for s, k in zip(sim, halves[h]) if not k]
            if not tr or not te:
                continue
            ct, rt, stt = em.build_reset([(s["c"], s["r"]) for s in tr])
            taut = np.concatenate([s["tau"] for s in tr])
            ot = em.fit(f, ct, rt, stt, True, n_starts=max(2, n_starts // 2), seed=seed + 7,
                        tau=taut,
                        extra_x0=cmpm.nested_starts(f, best_h.get((cmpm.NESTS.get(f), h))))
            best_h[(f, h)] = ot["params"]
            ce, re_, ste = em.build_reset([(s["c"], s["r"]) for s in te])
            taue = np.concatenate([s["tau"] for s in te])
            ll = em.trial_loglik(f, ot["params"], ce, re_, ste, True, True, taue)
            msk = cmpm.common_mask(ce, ste)
            ll_cv += float(np.nansum(ll[msk]))
            n_cv += int(msk.sum())
        row["cv_ll_per_trial"] = ll_cv / max(n_cv, 1)
        row["n_responded"] = n_resp
        out[f] = row
    return out


def run_job(args):
    gen, animal, params, sess, lrand, n_starts, seed = args
    sim = es.simulate_like(gen, params, sess, lrand, seed=seed)
    fits = fit_all(sim, n_starts, seed)
    fit_rows = [{"generator": gen, "animal": animal, "fitted": f, **v} for f, v in fits.items()]
    sig = signature(sim).assign(generator=gen, animal=animal)
    return fit_rows, sig


# ---------------------------------------------------------------------------
def confusion(fr: pd.DataFrame, score: str, higher_better: bool) -> pd.DataFrame:
    piv = fr.pivot_table(index=["generator", "animal"], columns="fitted", values=score)
    win = piv.idxmax(axis=1) if higher_better else piv.idxmin(axis=1)
    tab = pd.crosstab(win.index.get_level_values(0), win.values, normalize="index")
    tab.index.name, tab.columns.name = "generator", "winner"
    return tab.reindex(index=[m for m in MODELS if m in tab.index],
                       columns=MODELS).fillna(0.0)


def param_recovery(fr: pd.DataFrame, true: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for g in MODELS:
        rec = fr[(fr["generator"] == g) & (fr["fitted"] == g)].set_index("animal")
        tr = true[true["model"] == g].set_index("animal")
        for lbl in em.MODELS[g].labels:
            col = f"par_{lbl}"
            x = tr[col].reindex(rec.index).to_numpy(float)
            y = rec[col].to_numpy(float)
            ok = np.isfinite(x) & np.isfinite(y)
            if ok.sum() < 5:
                continue
            rows.append({"model": g, "param": lbl, "n": int(ok.sum()),
                         "spearman_r": spearmanr(x[ok], y[ok]).statistic,
                         "pearson_r": pearsonr(x[ok], y[ok]).statistic,
                         "median_true": np.median(x[ok]), "median_recovered": np.median(y[ok]),
                         "median_abs_error": np.median(np.abs(y[ok] - x[ok]))})
    return pd.DataFrame(rows)


def hazard_control(fr: pd.DataFrame, true: pd.DataFrame) -> pd.DataFrame:
    """b of belief_vhr / belief_CK_vhr fitted to non-anticipating simulations vs real."""
    rows = []
    for vhr in ["belief_vhr", "belief_CK_vhr"]:
        real = true[true["model"] == vhr].set_index("animal")["par_b"]
        rows.append({"vhr_model": vhr, "data": "real animals", "median_b": real.median(),
                     "frac_b_gt_0.01": float((real > 0.01).mean()), "n": len(real),
                     "real_minus_sim_median": np.nan, "animals_real_gt_sim": "",
                     "wilcoxon_p": np.nan})
        for g in MODELS:
            sim = fr[(fr["generator"] == g) & (fr["fitted"] == vhr)].set_index("animal")["par_b"]
            both = pd.concat([real, sim], axis=1, keys=["real", "sim"]).dropna()
            d = both["real"] - both["sim"]
            rows.append({"vhr_model": vhr, "data": f"simulated {g}", "median_b": sim.median(),
                         "frac_b_gt_0.01": float((sim > 0.01).mean()), "n": len(sim),
                         "real_minus_sim_median": d.median(),
                         "animals_real_gt_sim": f"{int((d > 0).sum())}/{len(d)}",
                         "wilcoxon_p": wilcoxon(d).pvalue if len(d) >= 5 and np.any(d != 0)
                         else np.nan})
    return pd.DataFrame(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", type=Path, default=CSV_PATH)
    ap.add_argument("--fits", type=Path, default=FITS_CSV)
    ap.add_argument("--out", type=Path, default=OUT_DIR)
    ap.add_argument("--generators", nargs="+", default=MODELS)
    ap.add_argument("--animals", nargs="+", default=None)
    ap.add_argument("--n-starts", type=int, default=N_STARTS)
    ap.add_argument("--jobs", type=int, default=1)
    args = ap.parse_args()
    out = args.out
    out.mkdir(parents=True, exist_ok=True)

    df = pd.read_csv(args.csv, low_memory=False)
    coh = df[df["lesioned"].isna() & (df["meets_criteria"] == True)]   # noqa: E712
    lrand = es.empirical_lrandom(coh)
    sessions = cmpm.load_cohort(args.csv)
    # real hr_side per session, for the animals' signature
    hr = {s: d.sort_values("trial_idx")["hr_side"].to_numpy(float)
          for s, d in coh.groupby("session_file")}
    for s in sessions:
        s["hr_side"] = hr[s["session"]]
    by_animal = {}
    for s in sessions:
        by_animal.setdefault(s["animal"], []).append(s)
    true = pd.read_csv(args.fits, dtype={"animal": str})
    true = true[true["scheme"] == "reset"]

    ck_fit, ck_sig = out / "fits_checkpoint.csv", out / "signature_checkpoint.csv"
    done = set()
    if ck_fit.exists():
        prev = pd.read_csv(ck_fit, dtype={"animal": str})
        done = set(zip(prev["generator"], prev["animal"]))
    # the animals' own signature
    if not ck_sig.exists():
        real_sig = pd.concat([signature(v).assign(generator="real", animal=a)
                              for a, v in by_animal.items()])
        real_sig.to_csv(ck_sig, index=False)

    jobs = []
    for gi, g in enumerate(args.generators):
        tg = true[true["model"] == g].set_index("animal")
        for ai, (a, sess) in enumerate(by_animal.items()):
            if (g, a) in done or (args.animals and a not in args.animals) or a not in tg.index:
                continue
            par = [tg.loc[a, f"par_{l}"] for l in em.MODELS[g].labels]
            jobs.append((g, a, par, sess, lrand, args.n_starts, 1000 * gi + ai))
    print(f"[jobs] {len(jobs)} (generator x animal) datasets to simulate and fit", flush=True)
    t0 = time.time()
    with Pool(args.jobs) as pool:
        for k, (fit_rows, sig) in enumerate(pool.imap_unordered(run_job, jobs), 1):
            pd.DataFrame(fit_rows).to_csv(ck_fit, mode="a", header=not ck_fit.exists(),
                                          index=False)
            sig.to_csv(ck_sig, mode="a", header=False, index=False)
            if k % 10 == 0 or k == len(jobs):
                print(f"[{k}/{len(jobs)}] {time.time() - t0:.0f}s", flush=True)

    fr = pd.read_csv(ck_fit, dtype={"animal": str})
    cb = confusion(fr, "bic", higher_better=False)
    ca = confusion(fr, "aic", higher_better=False)
    cc = confusion(fr, "cv_ll_per_trial", higher_better=True)
    cb.to_csv(out / "confusion_bic.csv")
    ca.to_csv(out / "confusion_aic.csv")
    cc.to_csv(out / "confusion_cv.csv")
    pr = param_recovery(fr, true)
    pr.to_csv(out / "param_recovery.csv", index=False)
    hc = hazard_control(fr, true)
    hc.to_csv(out / "hazard_slope_control.csv", index=False)

    sig = pd.read_csv(ck_sig, dtype={"animal": str})
    sig_m = (sig[sig["size"] >= 5].groupby(["generator", "tau"])["mean"].mean()
             .unstack("tau").round(3))
    fmt = lambda x: x.to_string(float_format=lambda v: f"{v:.3g}")  # noqa: E731
    lines = [
        "Parameter recovery, model confusion and non-anticipating agents on the exact task",
        "=" * 80,
        "",
        "Confusion, in-sample BIC: P(winner | generator)",
        fmt(cb), "",
        "Confusion, 2-fold CV held-out LL: P(winner | generator)",
        fmt(cc), "",
        "Confusion, AIC", fmt(ca), "",
        "Parameter recovery (f = g, 31 animals' parameters)",
        pr.to_string(index=False, float_format=lambda v: f"{v:.3g}"), "",
        "Hazard slope b fitted to real vs simulated non-anticipating data (paired by animal)",
        hc.to_string(index=False, float_format=lambda v: f"{v:.3g}"), "",
        f"P(choose worse | tau), L_Random phase, mean over animals (tau 1..{TAU_MAX})",
        fmt(sig_m),
    ]
    (out / "report.txt").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
